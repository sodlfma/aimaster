def render_jmx_template(endpoint, method, plan):
    # 플러그인 의존성을 제거한 순정 JMeter ThreadGroup JMX 생성
    max_concurrency = plan[-1]['Target Concurrency'] if plan else 100
    
    xml_template = f'''<?xml version="1.0" encoding="UTF-8"?>
<jmeterTestPlan version="1.2" properties="5.0" jmeter="5.5">
  <hashTree>
    <TestPlan guiclass="TestPlanGui" testclass="TestPlan" testname="MW Perf-Agent Test Plan">
      <stringProp name="TestPlan.comments">Auto-generated by MW Perf-Agent</stringProp>
      <boolProp name="TestPlan.functional_mode">false</boolProp>
      <boolProp name="TestPlan.serialize_threadgroups">false</boolProp>
    </TestPlan>
    <hashTree>
      <ThreadGroup guiclass="ThreadGroupGui" testclass="ThreadGroup" testname="Standard Thread Group">
        <stringProp name="ThreadGroup.num_threads">{max_concurrency}</stringProp>
        <stringProp name="ThreadGroup.ramp_time">30</stringProp>
        <boolProp name="ThreadGroup.scheduler">true</boolProp>
        <stringProp name="ThreadGroup.duration">300</stringProp>
        <stringProp name="ThreadGroup.delay">0</stringProp>
      </ThreadGroup>
      <hashTree>
        <HTTPSamplerProxy guiclass="HttpTestSampleGui" testclass="HTTPSamplerProxy" testname="{method} {endpoint}">
          <stringProp name="HTTPSampler.domain">{endpoint}</stringProp>
          <stringProp name="HTTPSampler.method">{method}</stringProp>
        </HTTPSamplerProxy>
        <hashTree/>
      </hashTree>
    </hashTree>
  </hashTree>
</jmeterTestPlan>'''
    return xml_template

